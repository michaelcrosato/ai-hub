/**
 * lines.js — everything Iona Quade (the Signal Nine host) can say, the
 * fictional sponsors, and the story archive. Pure data; host.js decides when
 * a line plays.
 */

/** Numbered commentary variants: lines('room.jackpot', 'excited', 'text', …). */
function lines(key, emotion, ...texts) {
  return texts.map((text, n) => ({
    id: `iona.v2.${key}.${String(n + 1).padStart(2, "0")}`,
    text,
    emotion,
  }));
}

/** Paid (fictional) sponsor transmissions read by Iona. */
function ads(sponsorId, key, ...texts) {
  return texts.map((text, n) => ({
    id: `sponsor.v2.${key}.${String(n + 1).padStart(2, "0")}`,
    text,
    emotion: "analysis",
    speaker: "iona",
    kind: "advertisement",
    sponsorId,
  }));
}

