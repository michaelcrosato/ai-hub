export function overall(e) {
  let t = e.r;
  return Math.round(
    {
      QB: (e) => e.arm * 0.35 + e.acc * 0.4 + e.spd * 0.15 + e.agi * 0.1,
      RB: (e) => e.spd * 0.35 + e.agi * 0.25 + e.str * 0.25 + e.hnd * 0.15,
      WR: (e) => e.spd * 0.4 + e.hnd * 0.4 + e.agi * 0.2,
      TE: (e) => e.hnd * 0.35 + e.str * 0.35 + e.spd * 0.3,
      OL: (e) => e.str * 0.8 + e.agi * 0.2,
      DE: (e) => e.str * 0.3 + e.spd * 0.3 + e.tkl * 0.4,
      DT: (e) => e.str * 0.5 + e.tkl * 0.5,
      LB: (e) => e.tkl * 0.45 + e.spd * 0.25 + e.cov * 0.3,
      CB: (e) => e.cov * 0.5 + e.spd * 0.35 + e.agi * 0.15,
      S: (e) => e.cov * 0.4 + e.tkl * 0.35 + e.spd * 0.25,
      K: (e) => e.kpw * 0.5 + e.kac * 0.5,
      P: (e) => e.kpw * 0.6 + e.kac * 0.4,
    }[e.pos](t),
  );
}
export function teamRatings(e) {
  let t = (e) => Math.round(e.reduce((e, t) => e + overall(t), 0) / Math.max(1, e.length)),
    n = t([
      ...byPos(e, `QB`).slice(0, 1),
      ...byPos(e, `RB`).slice(0, 1),
      ...byPos(e, `WR`).slice(0, 3),
      ...byPos(e, `TE`).slice(0, 1),
      ...byPos(e, `OL`).slice(0, 5),
    ]),
    r = t([
      ...byPos(e, `DE`).slice(0, 2),
      ...byPos(e, `DT`).slice(0, 2),
      ...byPos(e, `LB`).slice(0, 3),
      ...byPos(e, `CB`).slice(0, 2),
      ...byPos(e, `S`).slice(0, 2),
    ]),
    i = Math.round(e.roster.slice(0, 40).reduce((e, t) => e + t.r.spd, 0) / 40),
    a = t([...byPos(e, `K`), ...byPos(e, `P`)]),
    o = byPos(e, `QB`)[0];
  return { OFFENSE: n, DEFENSE: r, SPEED: i, PASSING: Math.round((o.r.arm + o.r.acc) / 2), KICKING: a };
}
