export const ACTS = ['The Outlander', 'The Nerevarine', 'The Tribunal', 'The Bloodmoon'];
export const ESSENTIAL = new Set(
  CAMPAIGN.flatMap((s) => [s.type === 'collect' ? s.target : null, ...(s.reward.items || [])])
    .filter(Boolean)
    .concat(['Wraithguard', 'Sunder', 'Keening']),
);
export function activeStep(state) {
  return CAMPAIGN[state.chapter] || null;
}
export function matchObjective(s, event) {
  return s && s.type === event.type && s.target === event.target && s.area === event.area;
}
export function gateForArea(area, state) {
  if (area.startsWith('wlk030') && !state.flags.morrowind) return 'The Mournhold chapter opens after the Heart is severed.';
  if (area.startsWith('wlk031') && !state.flags.tribunal) return 'The northern passage opens after the Tribunal chapter.';
  if (area === 'wlk029-15' && !state.flags.wraithguard)
    return 'Vivec’s counsel and Wraithguard are needed before entering Red Mountain.';
  return null;
}
