/** The district a world position belongs to. */
export function districtAt(x, z) {
  const id =
    Math.abs(x) < 78 && Math.abs(z) < 78
      ? 'mercury'
      : z < -105 && Math.abs(x) < 145
        ? 'crownline'
        : x < -105
          ? 'rustwater'
          : x > 105
            ? 'verdant'
            : z > 105
              ? 'ember'
              : 'nullworks';
  return DISTRICTS.find((d) => d.id === id);
}

/** A content entry by id; missing ids are a content bug, so they throw. */
export function byId(list, id) {
  const item = list.find((entry) => entry.id === id);
  if (!item) throw Error(`Missing content definition: ${id}`);
  return item;
}
